// Bundles the browser client and writes src/render/assets.generated.ts (spec 01 §5).
import { readFileSync, writeFileSync } from 'node:fs';
import { build, transform } from 'esbuild';

const client = await build({
  entryPoints: ['src/render/client/main.ts'],
  bundle: true,
  format: 'iife',
  target: 'es2020',
  minify: true,
  write: false,
  logLevel: 'warning',
});
const css = await transform(readFileSync('src/render/styles.css', 'utf8'), {
  loader: 'css',
  minify: true,
});
const template = readFileSync('src/render/template.html', 'utf8');
// The init templates travel inside the bundle, so `init` never has to find files next to the CLI.
const templates = Object.fromEntries(
  ['ROADMAP.md', 'DECISIONS.md', 'CHANGELOG.md', 'opmap.config.json', 'AGENTS.snippet.md'].map(
    (f) => [f, readFileSync(`templates/${f}`, 'utf8')],
  ),
);
const text = (client.outputFiles[0]?.text ?? '').trim();

// The fictional Tidepool project, for `init --example`.
const example = Object.fromEntries(
  [
    ['opmap.config.json', 'opmap.config.json'],
    ['ROADMAP.md', 'docs/project/ROADMAP.md'],
    ['DECISIONS.md', 'docs/project/DECISIONS.md'],
    ['CHANGELOG.md', 'CHANGELOG.md'],
  ].map(([key, f]) => [key, readFileSync(`examples/tidepool/${f}`, 'utf8')]),
);

writeFileSync(
  'src/render/assets.generated.ts',
  `// Generated by scripts/build-assets.mjs. Do not edit; not committed.\n` +
    `export const CLIENT_JS = ${JSON.stringify(text)};\n` +
    `export const STYLES_CSS = ${JSON.stringify(css.code.trim())};\n` +
    `export const TEMPLATE_HTML = ${JSON.stringify(template)};\n` +
    `export const INIT_TEMPLATES: Record<string, string> = ${JSON.stringify(templates)};\n` +
    `export const INIT_EXAMPLE: Record<string, string> = ${JSON.stringify(example)};\n`,
);
console.log(`assets: client ${text.length} bytes, styles ${css.code.length} bytes`);
